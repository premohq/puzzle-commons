//! Embeds every rendered cast sprite (assets/cast/*.png) so the game stays one self-contained file.
use std::fmt::Write;

fn main() {
    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../assets/cast");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut names: Vec<String> = std::fs::read_dir(&dir)
        .map(|r| r.filter_map(|e| e.ok()).map(|e| e.file_name().to_string_lossy().to_string()).filter(|n| n.ends_with(".png")).collect())
        .unwrap_or_default();
    names.sort();
    let mut s = String::from("/// Rendered cast sprites (generated by build.rs from assets/cast).\npub static CAST_FILES: &[(&str, &[u8])] = &[\n");
    for n in &names {
        let path = dir.join(n).canonicalize().unwrap();
        println!("cargo:rerun-if-changed={}", path.display());
        let _ = writeln!(s, "    ({:?}, include_bytes!({:?})),", &n[..n.len() - 4], path.display().to_string());
    }
    s.push_str("];\n");
    let out = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("cast_files.rs");
    std::fs::write(out, s).unwrap();
}
