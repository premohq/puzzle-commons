pub fn get(id: &str) -> &'static Member {
    CAST.iter().find(|m| m.id == id).unwrap_or(&CAST[0])
}
pub fn index(id: &str) -> usize {
    CAST.iter().position(|m| m.id == id).unwrap_or(0)
}

